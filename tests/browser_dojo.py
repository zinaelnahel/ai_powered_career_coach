"""Local-only dojo preview checks. Start Flask on port 5050 first."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.vendor'))
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as pw:
    browser = pw.chromium.launch(channel='chrome', headless=True)
    page = browser.new_page(viewport={'width': 1440, 'height': 1100})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:5050')
    expect(page.get_by_role('heading', name='Welcome to your dojo.')).to_be_visible()
    expect(page.locator('.dojo-belt-name')).to_have_text('White belt')
    expect(page.locator('.dojo-room')).to_have_count(4)
    expect(page.get_by_role('button', name='Classic view', exact=True)).to_have_count(0)
    expect(page.get_by_role('button', name='Dojo view', exact=True)).to_have_count(0)
    expect(page.locator('.sidebar nav [data-dojo-icon]')).to_have_count(5)
    for name in ['Leonardo', 'Raphael', 'Donatello', 'Michelangelo']:
        expect(page.get_by_role('img', name=name, exact=True)).to_be_visible()
    expect(page.get_by_role('img', name='Master Splinter', exact=False)).to_be_visible()
    expect(page.get_by_role('img', name='0 of 8 pizza slices earned')).to_be_visible()
    page.screenshot(path=str(ROOT / 'artifacts/dojo-desktop.png'), full_page=True)
    page.get_by_role('button', name='About this app', exact=True).click()
    expect(page.locator('#about')).to_be_visible()
    expect(page.locator('.zine-comic .zine-frame')).to_have_count(3)
    expect(page.locator('.zine-signature')).to_have_text('Zina El Nahel')
    expect(page.get_by_role('link', name="Let's connect on LinkedIn")).to_have_attribute('href', 'https://www.linkedin.com/in/zina-el-nahel')
    page.screenshot(path=str(ROOT / 'artifacts/dojo-about.png'), full_page=True)
    page.locator('#about summary').click()
    page.get_by_role('button', name='Manage my saved data', exact=True).click()
    expect(page.locator('#journey-settings')).to_be_visible()
    page.locator('.nav[data-page="overview"]').click()
    page.get_by_role('button', name='Open Mock interview', exact=True).click()
    expect(page.locator('#setup-form [data-dojo-icon=interview]')).to_be_visible()
    page.screenshot(path=str(ROOT / 'artifacts/dojo-interview-icons.png'), full_page=True)
    page.locator('#demo').check()
    page.locator('#interview-role').fill('AI QA Engineer')
    page.locator('#question-count').select_option('3')
    page.locator('#setup-form button').click()
    expect(page.locator('#answer')).to_be_visible()
    expect(page.locator('.message.assistant [data-dojo-icon=mentor]')).to_be_visible()
    if page.get_by_role('button', name='Dictate answer', exact=True).count():
        expect(page.get_by_role('button', name='Dictate answer', exact=True).locator('[data-dojo-icon=microphone]')).to_be_visible()
    page.locator('#answer').fill('My saved practice answer')
    page.locator('.nav[data-page="journey"]').click()
    page.locator('.nav[data-page="interview"]').click()
    expect(page.locator('#answer')).to_have_value('My saved practice answer')
    for index in range(3):
        page.locator('#answer').fill('I built accessible applications for 200 users and tested them with Playwright.')
        page.locator('#send').click()
        if index < 2:
            expect(page.locator('.message.assistant')).to_have_count(index + 2)
    expect(page.locator('#interview-report')).to_be_visible()
    page.locator('.nav[data-page="overview"]').click()
    expect(page.locator('.dojo-point-count strong')).to_have_text('75')
    expect(page.locator('.dojo-badge.earned')).to_have_count(1)
    page.get_by_role('button', name='Open CV reviewer', exact=True).click()
    expect(page.locator('#cv-form .panel-heading [data-dojo-icon=cv]')).to_be_visible()
    expect(page.locator('#cv-form [data-dojo-icon=upload]')).to_be_visible()
    page.locator('#cv-role').fill('AI QA Engineer')
    page.locator('#cv-text').fill('I built accessible React applications for 200 users. Skills: Python, Playwright and JavaScript. Education: Computer Science.')
    page.locator('#cv-form button[type="submit"]').click()
    expect(page.locator('#cv-report')).to_be_visible()
    page.locator('.nav[data-page="overview"]').click()
    expect(page.locator('.dojo-point-count strong')).to_have_text('125')
    expect(page.locator('.dojo-belt-name')).to_have_text('Green belt')
    expect(page.get_by_role('img', name='2 of 8 pizza slices earned')).to_be_visible()
    page.reload()
    expect(page.locator('.dojo-point-count strong')).to_have_text('125')
    page.get_by_role('button', name='Open Career Lab', exact=True).click()
    expect(page.locator('.lab-tabs [role="tab"]')).to_have_count(4)
    expect(page.locator('.lab-tabs [data-dojo-icon]')).to_have_count(4)
    page.screenshot(path=str(ROOT / 'artifacts/dojo-lab-icons.png'), full_page=True)
    page.locator('.nav[data-page="journey"]').click()
    page.get_by_role('tab', name='Goals & stories', exact=True).click()
    expect(page.locator('.career-memory .memory-icon:not(.dojo-icon)')).to_have_count(0)
    page.screenshot(path=str(ROOT / 'artifacts/journey-stories.png'), full_page=True)
    page.locator('.nav[data-page="journey"]').click()
    page.get_by_role('tab', name='History & feedback', exact=True).click()
    page.screenshot(path=str(ROOT / 'artifacts/journey-history.png'), full_page=True)
    rows = page.locator('#progress-list .history-row')
    expect(rows).to_have_count(2)
    rows.filter(has=page.get_by_role('paragraph').filter(has_text='Mock interview')).first.get_by_role('button', name='Delete', exact=True).click()
    page.get_by_role('button', name='Delete this session', exact=True).click()
    expect(rows).to_have_count(1)
    page.locator('.nav[data-page="overview"]').click()
    expect(page.locator('.dojo-point-count strong')).to_have_text('50')
    expect(page.locator('.dojo-belt-name')).to_have_text('White belt')
    page.set_viewport_size({'width': 390, 'height': 844})
    expect(page.get_by_role('heading', name='Welcome to your dojo.')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1')
    if page.locator('#dismiss-notice').count(): page.locator('#dismiss-notice').click()
    page.screenshot(path=str(ROOT / 'artifacts/dojo-mobile.png'), full_page=True)
    page.get_by_role('button', name='About this app', exact=True).click()
    expect(page.locator('#about')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1')
    assert not errors, errors
    browser.close()
    print('PASS: local dojo, turtle guides, dojo-only navigation, full demo interview/CV, persistent belts, individual deletion, all Lab tools and mobile layout.')
